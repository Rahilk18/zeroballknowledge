// Comprehensive EA Player ID dictionary for instant multi-tier fallback generation
export const EA_PLAYER_IDS: Record<string, string> = {};
Object.entries(PLAYER_AVATARS).forEach(([name, url]) => {
  const match = url.match(/p(\d+)\.png|players\/(\d+)\.png/);
  if (match) {
    const id = match[1] || match[2];
    const norm = name.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().trim();
    EA_PLAYER_IDS[name] = id;
    EA_PLAYER_IDS[norm] = id;

    const parts = name.split(' ');
    if (parts.length >= 2) {
      const initialShort = `${parts[0][0]}. ${parts.slice(1).join(' ')}`;
      const normInitial = initialShort.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().trim();
      EA_PLAYER_IDS[initialShort] = id;
      EA_PLAYER_IDS[normInitial] = id;

      const surname = parts[parts.length - 1];
      const normSurname = surname.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().trim();
      if (!EA_PLAYER_IDS[surname]) EA_PLAYER_IDS[surname] = id;
      if (!EA_PLAYER_IDS[normSurname]) EA_PLAYER_IDS[normSurname] = id;
    }
  }
});

